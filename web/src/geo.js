/* Расстояния и порядок объезда.
 *
 * Считается по прямой, а не по дорогам, и это осознанно. Маршрут по дорогам —
 * это платный Distance Matrix API и обращение к Яндексу на каждую пару точек:
 * на двадцати адресах пар почти четыреста, и суточный лимит уходит на один
 * рабочий день конструктора. Руководителю же нужно не расписание до минуты, а
 * порядок объезда и понимание «это полдня или весь день». Прямая с поправкой на
 * извилистость улиц (KROAD) отвечает на это с погрешностью, которая на фоне
 * разброса времени на самих адресах не значит ничего.
 *
 * Поэтому длина маршрута везде подписана «≈»: это оценка, а не обещание.
 */

/** Во сколько раз дорога длиннее прямой. Городская застройка с прямоугольной
 *  сеткой улиц даёт около 1.25–1.35; берём середину. */
export const KROAD = 1.3;

const RAD = Math.PI / 180;

/** Расстояние по прямой между точками, км. */
export function km(a, b) {
  const dLat = (b.lat - a.lat) * RAD;
  const dLon = (b.lon - a.lon) * RAD;
  const s = Math.sin(dLat / 2) ** 2
    + Math.cos(a.lat * RAD) * Math.cos(b.lat * RAD) * Math.sin(dLon / 2) ** 2;
  return 6371 * 2 * Math.asin(Math.min(1, Math.sqrt(s)));
}

/** Оценка длины объезда по порядку точек, км. */
export function routeKm(pts) {
  let sum = 0;
  for (let i = 1; i < pts.length; i++) sum += km(pts[i - 1], pts[i]);
  return sum * KROAD;
}

/**
 * Порядок объезда: ближайший сосед внутри окна приезда.
 *
 * Окно приезда клиенту назвал оператор, и переставлять адреса через него нельзя:
 * «с 10 до 12» — это обещание, а не пожелание. Поэтому точки сначала делятся по
 * окнам, окна идут по возрастанию, и ближайший сосед работает внутри окна,
 * начиная от последнего адреса предыдущего. Получается то, что руководитель и
 * собирал руками: сначала утренние адреса, и в каждом часе — по кругу без
 * возвратов через весь город.
 *
 * Эвристика простая и намеренно: она не ищет лучший маршрут, она убирает
 * очевидные метания. Порядок всё равно остаётся за руководителем — кнопка
 * только раскладывает точки, а не назначает их.
 */
export function orderPoints(pts) {
  const slots = [...new Set(pts.map((p) => p.time))].sort((a, b) => a - b);
  const out = [];
  let from = null;
  for (const slot of slots) {
    const left = pts.filter((p) => p.time === slot);
    while (left.length) {
      let best = 0;
      if (from) {
        let min = Infinity;
        left.forEach((p, i) => { const d = km(from, p); if (d < min) { min = d; best = i; } });
      }
      from = left.splice(best, 1)[0];
      out.push(from);
    }
  }
  return out;
}

/**
 * Ссылка «Открыть в Навигаторе».
 *
 * `yandexnavi://` открывает приложение Яндекс Навигатора и сразу строит маршрут
 * от текущего положения до точки. Если приложения нет — переход по такой ссылке
 * не делает ничего, поэтому рядом всегда стоит обычная ссылка на Яндекс Карты:
 * она откроется и в браузере телефона, и на компьютере у оператора.
 */
export const naviLink = (p) => `yandexnavi://build_route_on_map?lat_to=${p.lat}&lon_to=${p.lon}`;

/** Запасной путь: маршрут на Яндекс Картах в браузере. */
export const mapsLink = (p) => `https://yandex.ru/maps/?rtext=~${p.lat},${p.lon}&rtt=auto`;

/**
 * Открыть точку в Навигаторе.
 *
 * Проверить, установлено ли приложение, браузер не даёт: переход по
 * `yandexnavi://` либо открывает его, либо не делает ровно ничего, и разницы не
 * видно. Поэтому ставим отметку времени и через секунду смотрим, ушла ли
 * вкладка из вида: ушла — открылся Навигатор, осталась — приложения нет, и
 * открываем Яндекс Карты в браузере. У поверителя на телефоне сработает первое,
 * у оператора на компьютере — второе, и ни тому, ни другому ничего объяснять
 * не приходится.
 */
export function openNavi(lat, lon) {
  const p = { lat, lon };
  const back = () => { if (!document.hidden) window.open(mapsLink(p), '_blank', 'noopener'); };
  window.location.href = naviLink(p);
  setTimeout(back, 1000);
}
