/* Сверка инструкций с интерфейсом (пункт docs-train).
 *
 *   node check-names.mjs [out]   # код 0 — все названия из инструкций есть в web/src
 *
 * Из текста инструкций (content/*.mjs) берутся все названия в «кавычках» и
 * проверяются по исходникам интерфейса web/src: заголовки экранов, кнопки,
 * подписи, статусы. Название, которого в интерфейсе нет, — расхождение:
 * либо инструкция устарела, либо кнопку переименовали. Заодно проверяется,
 * что каждый скриншот, на который ссылается инструкция, лежит в shots/. */
import { readdirSync, readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { here, root } from './lib.mjs';

const SRC = join(root, 'web', 'src');
const files = [];
(function walk(d) { for (const f of readdirSync(d, { withFileTypes: true })) {
  const p = join(d, f.name); f.isDirectory() ? walk(p) : (/\.(js|css)$/.test(f.name) && files.push(p)); } })(SRC);
const source = files.map((f) => readFileSync(f, 'utf8')).join('\n');
/* Разметка собирается строками: у названий бывают HTML-сущности и разрывы —
   сравниваем по «сжатому» виду без пробелов и регистра. */
const squash = (s) => s.replace(/&nbsp;|&mdash;|&laquo;|&raquo;/g, ' ').replace(/[\s«»"'`·—–-]+/g, '').toLowerCase();
const haystack = squash(source);

/* Названия, которые в интерфейсе появляются с подстановкой, как часть текста
   или только в конкретном состоянии — сверяются по своей части. */
const ALIASES = {
  'В М… сегодня': 'сегодня',
  'Разложить по смене: N × 25': 'Разложить по смене',
  'На экран „Домой“': null,          // меню Safari, не наш интерфейс
  'Добавить на главный экран': null,  // меню Chrome
  'Поделиться': null,
  'На смене / Не на смене': 'На смене',
  'Сегодня / Завтра': 'Сегодня',
  'годен': 'годен', 'не годен': 'не годен',
  'Состояние → Уволены': 'Уволены',
  'Сущность → Услуги и прайс': 'Услуги и прайс',
  'Сущность → Услуги и прайс» или «Сотрудники и вход': 'Сотрудники и вход',
  'Заявки без маршрута': 'Заявки без маршрута',
  'выдан бланк': 'выдан бланк о непригодности',
  'ФГИС «Аршин»': 'ФГИС «Аршин»',
  'Клиент уже обращался': 'Клиент уже обращался',
  'Похоже на дубль': 'Похоже на дубль',
  'Приём закрыт': 'Приём закрыт',
  'план перебран': 'план перебран', 'день не запланирован': 'день не запланирован',
  'дата ушла под маршруты': 'дата ушла под маршруты',
  'позиция закрыта': 'позиция закрыта',
  'подтверждена / перенос / отказ': 'подтверждена',
  'оператор уже обработал': 'оператор уже обработал',
  '⋮': null,
  // Склонённые формы названий экранов и блоков.
  'Сменах операторов': 'Смены операторов', 'Моём маршруте': 'Мой маршрут', 'Поддержке маршрутов': 'Поддержка маршрутов',
  'Маршрутах этой сессии': 'Маршруты этой сессии', 'Сборке маршрутов': 'Сборка маршрутов',
  'Заявках без маршрута': 'Заявки без маршрута', 'Работах': 'Работы', 'Планировании дня': 'Планирование дня',
  'Планировании': 'Планирование дня', 'Мои заявки за сегодня': 'Мои заявки за сегодня',
  'вход закрыт до ЧЧ:ММ': 'вход закрыт до',
};

const outDir = process.argv[2] || join(here, 'content');
let problems = 0, checked = 0;
for (const f of readdirSync(outDir).filter((n) => n.endsWith('.mjs') && n !== 'common.mjs')) {
  const text = readFileSync(join(outDir, f), 'utf8');
  const names = new Set();
  for (const m of text.matchAll(/«([^»]{2,80})»/g)) names.add(m[1]);
  for (const n of names) {
    // Подзаголовки и обороты речи в кавычках названиями не считаются.
    if (/[.:!?]$/.test(n) || /^\d/.test(n) || /^на бумажке$/.test(n)) continue;
    const key = n in ALIASES ? ALIASES[n] : n;
    if (key === null) continue;
    // Составные названия через « / » или «→» — проверяем каждую часть.
    const parts = key.split(/\s\/\s|\s→\s/).map((s) => s.trim()).filter(Boolean);
    for (const part of parts) {
      checked++;
      if (!haystack.includes(squash(part))) { problems++; console.log(`${f}: в интерфейсе не найдено «${part}»`); }
    }
  }
  for (const m of text.matchAll(/figure\('([a-z0-9-]+)'/g)) {
    checked++;
    if (!existsSync(join(here, 'shots', m[1] + '.png'))) { problems++; console.log(`${f}: нет скриншота ${m[1]}.png`); }
  }
}
console.log(`Проверено названий и скриншотов: ${checked}, расхождений: ${problems}`);
process.exit(problems ? 1 : 0);
