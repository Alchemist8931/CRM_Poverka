/* Сверка встроенных подсказок интерфейса (подписи .cap) с инструкциями.
 *
 *   node check-caps.mjs   # код 0 — каждая подсказка экрана раскрыта в инструкциях
 *
 * Подсказка экрана — строка CAPS[view] в web/src/refs.js, её видит каждый, кто
 * открыл экран. Инструкция роли не должна ей противоречить и должна объяснять то
 * же самое: для каждой подсказки ниже перечислены её утверждения в виде
 * образцов, и каждый образец ищется в инструкциях тех ролей, у которых экран
 * есть в меню (GROUPS в refs.js). Утверждение, которого в инструкциях нет, —
 * расхождение. Заодно проверяется, что подсказка вообще есть и не изменилась
 * так, чтобы образцы перестали в ней находиться. */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { here, root } from './lib.mjs';

const refs = readFileSync(join(root, 'web', 'src', 'refs.js'), 'utf8');
const caps = Object.fromEntries([...refs.matchAll(/^\s{2}(\w+):'((?:[^'\\]|\\.)*)',?$/gm)].map((m) => [m[1], m[2]]));
const groups = Object.fromEntries([...refs.matchAll(/role:'(\w+)',\s*short:'[^']*',\s*views:\[([^\]]*)\]/g)]
  .map((m) => [m[1], m[2].split(',').map((s) => s.replace(/['\s]/g, '')).filter(Boolean)]));
if (!groups.supervisor) throw new Error('GROUPS в refs.js не разобраны');
// Экраны руководителя описаны и в инструкции администратора — это тот же человек.
const docOf = { operator: ['operator'], supervisor: ['supervisor', 'admin'], verifier: ['verifier'] };
const text = Object.fromEntries(['operator', 'supervisor', 'verifier', 'admin']
  .map((n) => [n, readFileSync(join(here, 'content', `${n}.mjs`), 'utf8').replace(/\s+/g, ' ')]));

const norm = (s) => s.replace(/[«»"„“*]/g, '').replace(/\s+/g, ' ').toLowerCase();

/* view → [ [образец в подсказке, образец в инструкции], … ]. Первый ищется в
   самой подсказке (чтобы сверка не отстала от интерфейса), второй — в инструкциях. */
const CLAIMS = {
  support: [
    ['шкале времени', /шкал[аеу] дня|по шкале/],
    ['позвонить', /позвонит|прозвон/],
    ['передвинуть по часам', /сдвига|передвин|на час/],
    ['добавить в маршрут новую', /в маршрут/],
  ],
  routes: [
    ['карту области', /карт[аеу]/],
    ['порядок нажатия задаёт последовательность объезда', /по порядку объезда|порядк[еу] объезда/],
    ['приём по ней закрывается', /приём.{0,40}закры|закры.{0,40}приём/],
    ['только руководитель', /заявка на дату/],
  ],
  schedule: [
    ['клик по клетке', /клик по клетке|нажмите на клетку|клетк/],
    ['та же смена, что в планировании', /планировани/],
  ],
  me: [
    ['собственный заработок', /мой заработок/],
    ['подотчёт', /подотч[её]т/],
  ],
  payroll: [
    ['подотчёт бригады', /подотч[её]т бригады/],
    ['сколько уже сдали', /принять возврат|сдал/],
  ],
  services: [
    ['физических и юридических', /физ|юр/],
    ['сдельные ставки', /ставк/],
  ],
  myroute: [
    ['заполняет акт', /акт/],
    ['услуга в строке прибора', /услуг/],
    ['фото выполненных работ', /фото/],
  ],
  absence: [
    ['до согласования дни остаются рабочими', /согласован/],
  ],
  arshin: [
    ['ФГИС «Аршин»', /аршин/],
    ['включая непригодные', /непригодн/],
    ['собирает выгрузку', /собрать выгрузку|выгрузк/],
    ['по рабочим дням', /рабочи[хм] дн/],
  ],
  staff: [
    ['временный пароль показывается один раз', /один раз/],
    ['при первом входе', /перв(ом|ый) вход/],
    ['блокировка', /заблокир/],
    ['остаётся в истории', /истори/],
  ],
  audit: [
    ['кто, когда и с какого адреса', /кто.{0,30}когда/],
    ['разницу по полям', /разниц|по полям/],
    ['три года', /три года|3 года/],
  ],
};

let problems = 0, checked = 0;
for (const [view, claims] of Object.entries(CLAIMS)) {
  const cap = caps[view];
  if (!cap) { console.log(`✗ ${view}: подсказки CAPS.${view} в refs.js нет`); problems++; continue; }
  const roles = Object.entries(groups).filter(([, v]) => v.includes(view)).map(([r]) => r);
  const docs = roles.flatMap((r) => docOf[r]);
  for (const [inCap, inDoc] of claims) {
    checked++;
    if (!norm(cap).includes(norm(inCap))) { console.log(`✗ ${view}: в подсказке больше нет «${inCap}» — обновить сверку и инструкции`); problems++; continue; }
    const hit = docs.filter((d) => inDoc.test(norm(text[d])));
    if (!hit.length) { console.log(`✗ ${view}: подсказка говорит «${inCap}», в инструкциях ${docs.join(', ')} этого нет`); problems++; }
  }
}
for (const view of Object.keys(caps)) if (!CLAIMS[view]) { console.log(`✗ ${view}: подсказка есть в интерфейсе, а сверки для неё нет`); problems++; }
console.log(`Подсказок экранов: ${Object.keys(caps).length}, утверждений проверено: ${checked}, расхождений: ${problems}`);
process.exit(problems ? 1 : 0);
