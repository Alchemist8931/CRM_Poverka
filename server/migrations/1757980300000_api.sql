-- Что понадобилось API сверх схемы прототипа (пункт be-api).
--
-- В прототипе «конструктор маршрутов открыт на эту дату» было состоянием вкладки
-- браузера (S.rc), и оно же закрывало дату для приёма. На сервере такого состояния
-- нет: оператор и руководитель сидят в разных браузерах, а за балансировщиком
-- может стоять и второй экземпляр приложения. Поэтому замок стал строкой в базе —
-- иначе правило dayLock работало бы только у того, кто конструктор и открыл.

-- Up Migration

CREATE TABLE route_builder (
  date      date PRIMARY KEY,
  staff_id  text NOT NULL REFERENCES staff (id) ON DELETE CASCADE,
  opened_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE route_builder IS
  'Открытый конструктор маршрутов: дата, кто открыл и когда. Строка живёт до явного '
  'закрытия, но замок считается снятым через два часа — забытое окно не должно '
  'держать приём закрытым до конца времён.';

-- Down Migration
DROP TABLE route_builder;
