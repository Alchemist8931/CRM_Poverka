-- Учётные записи сотрудников (пункт be-users).
--
-- Поля доступа завела ещё be-schema — логин, хеш пароля, признак «пароль
-- временный», отметка блокировки. Здесь к ним добавляется то, без чего учётками
-- нельзя управлять руками руководителя, а не разработчика:
--
--   email          — почта сотрудника: из неё по умолчанию собирается логин, на
--                    неё же уйдёт письмо, когда появится рассылка служебных писем;
--   failed_logins  — подряд идущие неудачные попытки входа;
--   locked_until   — до какого времени вход закрыт после пяти неудач подряд;
--   sessions_from  — «выйти со всех устройств»: сессии, выданные раньше этой
--                    отметки, не принимаются.
--
-- Почему `sessions_from`, а не список сессий: сессия — подписанная cookie и
-- состояния на сервере не держит (`src/api/auth.ts`), это и позволяет держать
-- два экземпляра приложения за балансировщиком. Одна отметка времени гасит
-- сразу все выданные раньше и стоит одного столбца вместо таблицы, которую
-- пришлось бы ещё и чистить.
--
-- Новых таблиц пункт не заводит: человек и его доступ — одна карточка, так
-- решено в архитектуре и так лежит в `staff`.

-- Up Migration

ALTER TABLE staff
  ADD COLUMN email         text,
  ADD COLUMN failed_logins integer NOT NULL DEFAULT 0,
  ADD COLUMN locked_until  timestamptz,
  ADD COLUMN sessions_from timestamptz;

COMMENT ON COLUMN staff.email IS
  'Почта сотрудника. Из неё по умолчанию собирается логин (часть до «@»); '
  'вход всё равно идёт по логину, а не по почте.';
COMMENT ON COLUMN staff.failed_logins IS
  'Неудачных попыток входа подряд. Обнуляется удачным входом и сбросом пароля.';
COMMENT ON COLUMN staff.locked_until IS
  'До этого времени вход закрыт: пять неудач подряд закрывают его на 15 минут. '
  'Это не увольнение — увольнение это blocked_at, и оно бессрочно.';
COMMENT ON COLUMN staff.sessions_from IS
  'Выход со всех устройств: сессия, выданная раньше этой отметки, не принимается. '
  'Ставится при смене и сбросе пароля и по кнопке в карточке.';

-- Почта, как и логин, не чувствительна к регистру и не повторяется: иначе два
-- человека получат один адрес для писем и одинаковый логин по умолчанию.
CREATE UNIQUE INDEX staff_email_key ON staff (lower(email)) WHERE email IS NOT NULL;

