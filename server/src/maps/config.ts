/* Настройки Яндекс Карт: два разных ключа и срок хранения координат.
 *
 * Ключей именно два, и путать их нельзя.
 *
 *  — Ключ JavaScript API живёт в браузере. Спрятать его невозможно в принципе:
 *    он уходит в адрес загрузки библиотеки, и его видно в любой вкладке. Защищает
 *    его не секретность, а ограничение по домену (HTTP Referer) в кабинете
 *    разработчика: с чужого сайта запрос с таким ключом отвергается. Поэтому
 *    фронт получает его от сервера (GET /api/maps/config), а не из сборки —
 *    иначе он оказался бы в репозитории, откуда его не вычистить.
 *
 *  — Ключ Геокодера живёт только на сервере. Геокодирование делает сервер при
 *    сохранении заявки, и ключ не выходит за пределы машины. Его ограничивают не
 *    доменом, а тем, что он никуда не отдаётся.
 *
 * Оба приезжают из Lockbox по сервисному аккаунту ВМ (src/secrets.ts); на машине
 * разработчика — из окружения. Ключей нет — система работает: конструктор рисует
 * прежнюю схематичную карту области, а заявка сохраняется без координат.
 *
 * GEO_CACHE_DAYS — не про производительность. Условия использования API Яндекс
 * Карт (ред. 01.09.2026) разрешают бесплатной лицензии держать ответ Геокодера
 * не дольше 30 суток; по истечении срока адрес геокодируется заново. Ноль —
 * «хранить бессрочно», и включать его можно только с коммерческой лицензией,
 * которая право на хранение даёт. Разбор — docs/maps.md.
 */

export interface MapsConfig {
  /** Ключ HTTP Геокодера. Только сервер. */
  geocoderKey: string | null;
  /** Ключ JavaScript API. Отдаётся браузеру, ограничивается доменом. */
  jsApiKey: string | null;
  /** Адрес Геокодера. Переменная нужна проверкам: они поднимают свой приёмник. */
  geocoderUrl: string;
  /** Сколько суток ответ Геокодера считается годным. 0 — бессрочно. */
  cacheDays: number;
  /** Окно предпочтения для поиска: юго-запад и северо-восток Свердловской области. */
  bbox: string;
  /** Что приписывается к адресу заявки перед поиском: в базе города без области. */
  region: string;
  /** Сколько ждать ответа Геокодера, мс. Приём заявки его не ждёт, но и висеть незачем. */
  timeoutMs: number;
}

const str = (v: string | undefined): string | null => {
  const s = v?.trim();
  return s ? s : null;
};

/** Предел из условий Яндекса: дольше держать ответ бесплатная лицензия не даёт. */
export const FREE_CACHE_DAYS_MAX = 30;

export function mapsConfig(env: NodeJS.ProcessEnv = process.env): MapsConfig {
  const days = Number(env.GEO_CACHE_DAYS);
  return {
    geocoderKey: str(env.YANDEX_GEOCODER_KEY),
    jsApiKey: str(env.YANDEX_JSAPI_KEY),
    geocoderUrl: str(env.YANDEX_GEOCODER_URL) ?? 'https://geocode-maps.yandex.ru/1.x/',
    cacheDays: Number.isFinite(days) && days >= 0 ? days : FREE_CACHE_DAYS_MAX,
    bbox: str(env.YANDEX_GEOCODER_BBOX) ?? '57.2,56.2~64.2,60.0',
    region: str(env.YANDEX_GEOCODER_REGION) ?? 'Свердловская область',
    timeoutMs: Number(env.YANDEX_GEOCODER_TIMEOUT_MS) || 8000,
  };
}

/** Есть ли чем геокодировать. Без ключа заявка сохраняется без координат. */
export const canGeocode = (cfg: MapsConfig): boolean => !!cfg.geocoderKey;

/** Точность, при которой точке можно верить и вести по ней поверителя. */
export const PRECISE = new Set(['exact', 'number', 'near', 'range']);
