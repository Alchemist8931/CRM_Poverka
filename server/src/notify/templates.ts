/* Шаблоны сообщений: подстановки, рендер и проверка при сохранении.
 *
 * Тексты пишет руководитель на экране «Услуги и ставки», а не программист в
 * коде: «ожидайте мастера» или «ожидайте специалиста» — это его решение, и
 * менять его выкладкой новой версии никуда не годится.
 *
 * Отсюда правило: опечатку в имени подстановки ловим при сохранении шаблона, а
 * не при отправке. Иначе клиент получает письмо со строкой «{имя_поверителя}»
 * посреди текста, и узнаём мы об этом от него же.
 */

/** Событие, по которому уходит сообщение. «чек» — чек по безналичной оплате
 *  зарегистрирован кассой и отправлен клиенту (пункт int-pay). */
export type NotifyEvent = 'заявка' | 'напоминание' | 'выезд' | 'перенос' | 'чек';
export const EVENTS: NotifyEvent[] = ['заявка', 'напоминание', 'выезд', 'перенос', 'чек'];

/** Канал доставки.
 *
 *  MAX здесь нарочно отсутствует. Заказчик на вопрос о канале рассылки ответил
 *  «МАКС??» — то есть выбор не сделан, и мессенджер в перечень каналов не
 *  попадает до ответа. Место под него готово: у канала нет ничего, кроме имени
 *  в этом типе, отправителя в `notifier.ts` и пары строк в CHECK миграции.
 *  Как его добавить — описано в docs/notify.md, раздел «MAX». */
export type Channel = 'email' | 'sms';
export const CHANNELS: Channel[] = ['email', 'sms'];

/** Что можно подставить и что это значит. Перечень показывается руководителю
 *  рядом с полем ввода: без него шаблон правится наугад. */
export const PLACEHOLDERS: Record<string, string> = {
  'имя': 'как клиент представился при приёме',
  'дата': 'дата выезда, 14.09.2026',
  'прежняя_дата': 'дата, с которой перенесли (только событие «перенос»)',
  'окно_с': 'начало окна прибытия, 11:00',
  'окно_до': 'конец окна прибытия, 13:00',
  'адрес': 'город, улица, дом и квартира',
  'услуги': 'что заказано: «Поверка счётчика воды»',
  'сумма': 'предварительная стоимость по прайсу, в рублях',
  'оплата': 'способы оплаты на месте: наличные или перевод; с эквайрингом — ещё QR СБП и ссылка',
  'поверитель': 'имя поверителя (только событие «выезд»)',
  'номер_чека': 'номер кассового чека (только событие «чек»)',
  'сумма_оплаты': 'сколько оплачено по чеку, в рублях (только событие «чек»)',
  'почта': 'почта клиента, куда касса отправила чек (только событие «чек»)',
  'контора': 'короткое имя конторы из настроек',
  'телефон_конторы': 'телефон конторы из настроек',
  'подпись': 'подпись из настроек',
};

/** Подстановки, которых у события просто нет: в шаблоне «заявка» имя поверителя
 *  ещё неизвестно — маршрут собирается позже, и обещать его нельзя. */
const RECEIPT_ONLY = ['номер_чека', 'сумма_оплаты', 'почта'];
const NOT_IN: Record<NotifyEvent, string[]> = {
  'заявка': ['поверитель', 'прежняя_дата', ...RECEIPT_ONLY],
  'напоминание': ['поверитель', 'прежняя_дата', ...RECEIPT_ONLY],
  'выезд': ['прежняя_дата', ...RECEIPT_ONLY],
  'перенос': ['поверитель', ...RECEIPT_ONLY],
  // Чек уходит после выезда: окно и «предварительная сумма» ему ни к чему.
  'чек': ['прежняя_дата', 'окно_с', 'окно_до', 'сумма', 'оплата'],
};

/** Что можно подставить в шаблон этого события. */
export const allowedFor = (event: NotifyEvent): string[] =>
  Object.keys(PLACEHOLDERS).filter((name) => !NOT_IN[event].includes(name));

const MARK = /\{([а-яёa-z_]+)\}/gi;

/** Имена подстановок, встреченные в тексте. */
export const placeholdersIn = (text: string): string[] =>
  [...new Set([...text.matchAll(MARK)].map((m) => m[1]!))];

/**
 * Проверка шаблона перед сохранением: понятная человеку причина или null.
 * Пустой текст — тоже ошибка: пустое сообщение уходит клиенту так же исправно,
 * как заполненное, и выглядит как поломка системы.
 */
export function templateProblem(event: NotifyEvent, channel: Channel, subject: string, body: string): string | null {
  if (!body.trim()) return 'Текст сообщения пустой.';
  if (channel === 'email' && !subject.trim()) return 'У письма должна быть тема.';
  const allowed = allowedFor(event);
  for (const name of placeholdersIn(subject + '\n' + body)) {
    if (allowed.includes(name)) continue;
    const known = Object.keys(PLACEHOLDERS).includes(name);
    return known
      ? `Подстановки {${name}} нет у события «${event}»: ${PLACEHOLDERS[name]}.`
      : `Неизвестная подстановка {${name}}. Доступны: ${allowed.map((n) => '{' + n + '}').join(', ')}.`;
  }
  return null;
}

/**
 * Подставляет значения в текст.
 *
 * Неизвестное или пустое имя оставляет пустую строку, а не выражение в скобках:
 * шаблон проверен при сохранении, и если сюда всё-таки пришла лишняя скобка,
 * клиенту лучше увидеть пропуск, чем кусок разметки.
 */
export function render(text: string, vars: Record<string, string | number | null | undefined>): string {
  return text.replace(MARK, (_, name: string) => {
    const value = vars[name];
    return value === null || value === undefined ? '' : String(value);
  });
}
