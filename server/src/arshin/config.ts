/* Настройки обмена с ФГИС «Аршин» (пункт int-arshin).
 *
 * Обмен бывает двух видов, и какой из них у заказчика — решает сам заказчик
 * (вопрос задан пунктом req-blockers, ответа на день выкладки нет):
 *
 *   • «файл» — система формирует XML установленного формата, руководитель
 *     загружает его в личном кабинете ФГИС Росаккредитации и вносит обратно
 *     номера записей. Работает без единого доступа и потому включён по
 *     умолчанию;
 *   • «API» — та же запись уходит обращением к реестру по договору. Включается
 *     ARSHIN_API_URL и ARSHIN_API_TOKEN; пока их нет, канал выключен и очередь
 *     живёт файлом.
 *
 * Условный шифр (ARSHIN_ORG_CODE) присваивает Росстандарт каждому лицу,
 * передающему сведения, — пункт 25 приказа Минпромторга России от 28.08.2020
 * № 2906. Без него запись реестр не примет, поэтому пустой шифр очередь считает
 * ошибкой записи, а не молчаливо отправляет пустое поле.
 */

export type Channel = 'файл' | 'API';

export interface ArshinConfig {
  /** Наименование аккредитованного лица — подпункт «п» пункта 26 приказа № 2906. */
  orgName: string;
  /** Условный шифр, присвоенный Росстандартом, — пункт 25 того же приказа. */
  orgCode: string;
  /** Адрес API реестра. Пусто — обмена по API нет. */
  apiUrl: string;
  apiToken: string;
}

export function arshinConfig(env: NodeJS.ProcessEnv = process.env): ArshinConfig {
  return {
    orgName: env.ARSHIN_ORG_NAME?.trim() ?? '',
    orgCode: env.ARSHIN_ORG_CODE?.trim().toUpperCase() ?? '',
    apiUrl: env.ARSHIN_API_URL?.trim() ?? '',
    apiToken: env.ARSHIN_API_TOKEN?.trim() ?? '',
  };
}

/** Есть ли чем ходить в реестр самим. Нет — остаётся файл, и это рабочий путь,
 *  а не поломка: в личном кабинете сведения принимают тем же файлом. */
export const canSend = (cfg: ArshinConfig): boolean => !!(cfg.apiUrl && cfg.apiToken);

/** Каким каналом уйдёт следующая выгрузка. */
export const channelOf = (cfg: ArshinConfig): Channel => (canSend(cfg) ? 'API' : 'файл');
