/* Заготовки для проверок импорта: пустая база, книга справочников, клиентская база.
 *
 * Книга справочников — не выдумка, а тот самый файл, который ушёл заказчику в
 * пункте req-refs: `test/fixtures/refs-template.xlsx`. В нём в каждом листе стоит
 * строка-пример, и прогон импорта по ней — это и есть сверка «шаблон с примерами
 * заполняет базу».
 *
 * Клиентская база собирается здесь же кодом и нарочно кривая: телефон через
 * восьмёрку и через плюс, один и тот же человек тремя строками, адрес одной
 * строкой в трёх разных написаниях, битая дата, город не из справочника,
 * строка без телефона. Ровно то, что придёт из старого учёта.
 */
import { readFileSync, readdirSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PGlite } from '@electric-sql/pglite';
import ExcelJS from 'exceljs';
import type { SqlRunner } from '../scripts/import/db.mts';

const serverDir = fileURLToPath(new URL('..', import.meta.url));

/** Книга справочников, отправленная заказчику в пункте req-refs. */
export const REFS_TEMPLATE = join(serverDir, 'test', 'fixtures', 'refs-template.xlsx');

export interface TestDb extends SqlRunner { close(): Promise<void> }

/** Пустая база со всей схемой: те же миграции, что на живом сервере. */
export async function freshDb(): Promise<TestDb> {
  const pg = new PGlite();
  const dir = join(serverDir, 'migrations');
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.sql')).sort()) {
    const sql = readFileSync(join(dir, file), 'utf8');
    await pg.exec(sql.split('-- Down Migration')[0]!.split('-- Up Migration')[1] ?? '');
  }
  return {
    query: (text, params) => pg.query(text, params as never[]) as never,
    close: () => pg.close(),
  };
}

